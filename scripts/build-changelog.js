#!/usr/bin/env node
// Regenerates js/changelog-data.js from CHANGELOG.md. Run manually, or automatically
// via the pre-commit hook (see scripts/pre-commit) whenever CHANGELOG.md changes.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const changelogPath = path.join(root, 'CHANGELOG.md');
const outPath = path.join(root, 'js', 'changelog-data.js');

const markdown = fs.readFileSync(changelogPath, 'utf8');

const escaped = markdown
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');

const output = `// Auto-generated by scripts/build-changelog.js from CHANGELOG.md -- do not edit by hand.
window.CHANGELOG_MARKDOWN = \`${escaped}\`;
`;

fs.writeFileSync(outPath, output);
console.log('Wrote ' + path.relative(root, outPath));
